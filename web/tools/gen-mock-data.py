#!/usr/bin/env python3
# Regenerates web/js/mock-data.js: a few results of the Python reference (fixtures/generated/*.jsonl.gz) converted
# into response objects of docs/WASM-API.md, for the mock engine of the page. Usage (from the repository root):
#     python3 web/tools/gen-mock-data.py > web/js/mock-data.js
# Compact form (expanded by engine-mock.js): `url` without the uops.info prefix; runs of 4 or more equal
# characters in `text` are written as  <char>~<count>~ .
import gzip, json, re, sys

WANT = [('addimm_chain2.o', 'SKL'), ('sf_64to32.o', 'ZEN3'), ('s2_0610.o', 'ADL-P'), ('eigen_s1_0284.o', 'SKL')]
URL_PREFIX = 'https://www.uops.info/html-instr/'
LINK = re.compile(r'\x1b\]8;;([^\x07\x1b]*)(?:\x07|\x1b\\)')  # terminal hyperlink: ESC ] 8 ; ; url (BEL | ESC \)

def load(path):
    found = {}
    with gzip.open(path, 'rt') as f:
        for line in f:
            c = json.loads(line)
            if (c['file'], c['arch']) in WANT and not c['options']:
                c.pop('json', None)
                found[(c['file'], c['arch'])] = c
    return found

def num(s):
    v = float(s)
    return int(v) if v == int(v) else v

def spans(seg):
    return [(m.group(), m.start(), m.end()) for m in re.finditer(r'\S+(?: \S+)*', seg)]

def assign(header, seg):  # the values of a row segment, by the header name they are printed under
    hs = spans(header)
    out = [0] * len(hs)
    for tok, a, b in spans(seg):
        i = min(range(len(hs)), key=lambda i: abs((hs[i][1] + hs[i][2]) / 2 - (a + b) / 2))
        assert out[i] == 0
        out[i] = num(tok)
    return out

def rle(text):
    assert '~' not in text
    return re.sub(r'(.)\1{3,}', lambda m: '%s~%d~' % (m.group(1), len(m.group())), text)

def convert(sim, instrs):
    raw = sim['stdout']
    text = LINK.sub('', raw)
    lines = raw.split('\n')
    r = {'arch': sim['arch'], 'tp': sim['TP'], 'mode': 'loop', 'decodeErrors': 0}
    b = re.search(r'^Bottlenecks?: (.*)$', text, re.M).group(1)
    r['bottlenecks'] = [] if b == 'unknown' else b.split(', ')
    r['limits'] = [{'name': n, 'tp': float(v)} for n, v in re.findall(r'^  - (\w+): ([\d.]+)$', text, re.M)]
    hi = next(i for i, l in enumerate(lines) if l.startswith('│ MITE'))
    hseg = lines[hi].split('│')
    r['columns'] = [h for s in hseg[1:5] for h, _, _ in spans(s)]
    rows, k, total = [], 0, None
    for l in lines[hi + 2:]:
        if not l.startswith('│'):
            continue
        seg = l.split('│')
        vals = [v for j in range(1, 5) for v in assign(hseg[j], seg[j])]
        note, label = seg[5].strip(), seg[6].strip()
        m = LINK.match(label)
        url = m.group(1) if m else None
        label = LINK.sub('', label)
        if label == 'Total':
            total = vals
        elif label.startswith('<'):
            rows.append({'kind': 'stackSync' if 'Stack' in label else 'regMerge', 'label': label, 'notes': note, 'values': vals})
        else:
            i = instrs[k]
            k += 1
            assert i['asm'] == label, (i['asm'], label)
            assert url is None or url.startswith(URL_PREFIX)
            rows.append({'kind': 'instr', 'label': label, 'opcode': i['opcode'], 'instrStr': i['instrStr'],
                         'url': url and url[len(URL_PREFIX):], 'notes': note, 'values': vals})
    assert k == len(instrs)
    for j, t in enumerate(total):  # the rows must add up to uiCA's "Total" line
        assert abs(sum(x['values'][j] for x in rows) - t) < 0.035, (sim['file'], r['columns'][j])
    r['rows'] = rows
    r['text'] = rle(text)
    r['trace'] = None
    return {'hex': sim['hex'].lower(), 'source': sim['file'], 'response': r}

sims = load('fixtures/generated/sim_fixtures.jsonl.gz')
instrs = load('fixtures/generated/instr_fixtures.jsonl.gz')
cases = [convert(sims[k], instrs[k]['instrs']) for k in WANT]
print('// Generated by web/tools/gen-mock-data.py from the fixtures of the Python reference; do not edit.')
print('// Each entry: the machine code, the fixture file it comes from, and the result as a response of docs/WASM-API.md')
print('// in a compact form (see expand() in engine-mock.js).')
print('export const RECORDED = [')
for c in cases:
    print('  ' + json.dumps(c, ensure_ascii=False, separators=(',', ':')) + ',')
print('];')
