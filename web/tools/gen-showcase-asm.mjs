// Generates web/js/showcase-asm.js: the SHA-256 showcase (showcase.js) as Intel-syntax assembly, made by the page's
// own conversion (asm-text.js bytesToAsm) and checked to assemble back to exactly the same bytes.
//   node web/tools/gen-showcase-asm.mjs [WASM] [ASM_WASM]
import fs from 'node:fs';
import { WasmEngine } from '../js/engine.js';
import { WasmAssembler } from '../js/assembler.js';
import { bytesToAsm } from '../js/asm-text.js';
import { hexToBytes, toHex } from '../js/hex-input.js';
import { SHA256_BLOCK_HEX } from '../js/showcase.js';

const root = new URL('../../', import.meta.url);
const wasmPath = process.argv[2] || new URL('target/wasm32-unknown-unknown/release/wuica_wasm.wasm', root);
const asmPath = process.argv[3] || new URL('assembler/dist/wuica_asm.wasm', root);
const engine = await WasmEngine.create(fs.readFileSync(wasmPath));
const assembler = await WasmAssembler.create(fs.readFileSync(asmPath));

const bytes = hexToBytes(SHA256_BLOCK_HEX.replace(/\s+/g, ''));
const r = await bytesToAsm(bytes, { decode: (hex) => engine.decode(hex, 'ALL'), assemble: (text) => assembler.assemble(text, 'intel') });
if (!r.ok) throw new Error('bytesToAsm failed: ' + JSON.stringify(r).slice(0, 300));
const back = await assembler.assemble(r.text, 'intel');
if (!back.ok || toHex(back.bytes) !== toHex(bytes)) throw new Error('the assembly does not assemble to the same bytes');

const out = `// Generated by web/tools/gen-showcase-asm.mjs from showcase.js: the SHA-256 showcase as Intel-syntax assembly that
// assembles to exactly the same ${bytes.length} bytes. Loaded only when the example is picked.
export const SHA256_BLOCK_ASM = ${JSON.stringify(r.text)};
`;
fs.writeFileSync(new URL('web/js/showcase-asm.js', root), out);
console.log(`web/js/showcase-asm.js: ${r.text.split('\n').length - 1} lines, ${out.length} bytes, ${r.fallback.length} .byte lines`);
